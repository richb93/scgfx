static const char **get_glyph(char c) {
    for (size_t i = 0; i < sizeof(font) / sizeof(font[0]); i++) {
        if (font[i].c == c) {
            return font[i].rows;
        }
    }

    return get_glyph(' ');
}

static int glyph_advance(char c) {
    return c == ' ' ? SPACE_W : CHAR_W;
}

static int text_pixel_width(const char *text) {
    int width = 0;

    for (size_t i = 0; text[i] != '\0'; i++) {
        width += glyph_advance(text[i]);
    }

    return width;
}

static int pixel_at(const char *text, int x, int y) {
    if (x < 0) return 0;
    if (y < 0 || y >= RENDER_H) return 0;

    int font_y = y / SCALE_Y;
    int char_start = 0;

    for (size_t i = 0; text[i] != '\0'; i++) {
        int advance = glyph_advance(text[i]);
        int col = x - char_start;

        if (col >= 0 && col < advance) {
            if (text[i] == ' ' || col >= 5) return 0;

            const char **g = get_glyph(text[i]);
            return g[font_y][col] == '1';
        }

        char_start += advance;
    }

    return 0;
}

static void write_frame(const char *text, int frame, int scroll_offset) {
    char filename[64];
    snprintf(filename, sizeof(filename), "frame_%04d.pbm", frame);

    FILE *f = fopen(filename, "w");
    if (!f) {
        perror(filename);
        exit(1);
    }

    fprintf(f, "P1\n%d %d\n", W, H);

    int y_offset = (H - RENDER_H) / 2;
    int scroll_x = W - scroll_offset;

    for (int y = 0; y < H; y++) {
        for (int x = 0; x < W; x++) {
            int text_x = x - scroll_x;
            int text_y = y - y_offset;

            fprintf(f, "%d ", pixel_at(text, text_x, text_y));
        }
        fprintf(f, "\n");
    }

    fclose(f);
}

static void usage(const char *prog) {
    fprintf(stderr,
        "Usage:\n"
        "  %s [-step N] text to scroll\n\n"
        "Options:\n"
        "  -step N     Scroll by N pixels per frame. Default is 1.\n"
        "              Higher values create fewer frames and faster movement.\n"
        "  -speed N    Alias for -step N.\n\n"
        "Example:\n"
        "  %s -step 2 Hello world\n",
        prog, prog);
}

int main(int argc, char **argv) {
    char text[1024];
    int step = 1;
    int first_text_arg = 1;

    text[0] = '\0';

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-h") == 0 ||
            strcmp(argv[i], "--help") == 0) {
            usage(argv[0]);
            return 0;
        } else if (strcmp(argv[i], "-step") == 0 ||
                   strcmp(argv[i], "--step") == 0 ||
                   strcmp(argv[i], "-speed") == 0 ||
                   strcmp(argv[i], "--speed") == 0) {
            if (i + 1 >= argc) {
                fprintf(stderr, "Missing value after %s\n", argv[i]);
                usage(argv[0]);
                return 1;
            }

            step = atoi(argv[++i]);

            if (step < 1) {
                fprintf(stderr, "Step/speed must be 1 or greater.\n");
                return 1;
            }

            first_text_arg = i + 1;
        } else {
            break;
        }
    }

    if (first_text_arg < argc) {
        for (int i = first_text_arg; i < argc; i++) {
            if (text[0] != '\0') strcat(text, " ");

            if (strlen(text) + strlen(argv[i]) + 2 >= sizeof(text)) {
                fprintf(stderr, "Text is too long.\n");
                return 1;
            }

            strcat(text, argv[i]);
        }
    } else {
        printf("Enter text: ");

        if (!fgets(text, sizeof(text), stdin)) {
            return 1;
        }

        text[strcspn(text, "\n")] = '\0';
    }

    int text_width = text_pixel_width(text);

    /*
       Scroll starts with the text completely off the right-hand side:
           scroll_offset = 0

       The final useful frame is when the last text pixel has just moved
       off the left-hand edge:
           scroll_offset = W + text_width - 1

       This avoids generating a tail of completely blank frames.
    */
    int max_scroll = W + text_width - 1;
    int frames = (max_scroll / step) + 1;

    for (int i = 0; i < frames; i++) {
        write_frame(text, i, i * step);
    }

    printf("Generated %d PBM frames. Step: %d pixel%s per frame.\n",
           frames, step, step == 1 ? "" : "s");

    return 0;
}
